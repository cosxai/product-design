class Logic extends DCLogic {
  dict = {
    zh: { t_neutral: '链接已复制。', t_complete: '3 个文件已移到归档。', t_error: '无法重命名文件夹。' },
    en: { t_neutral: 'Link copied.', t_complete: '3 files moved to Archive.', t_error: 'Couldn’t rename the folder.' },
  };
  state = Object.assign({ lang: this.pref('cosx-site-lang', 'en'), theme: this.pref('cosx-site-theme', 'light') }, { list: [] });
  pref(k, d) {
    try {
      return localStorage.getItem(k) || d;
    } catch (e) {
      return d;
    }
  }
  save(k, v) {
    try {
      localStorage.setItem(k, v);
    } catch (e) {}
  }
  componentDidMount() {
    this._sync = () => this.setState({ lang: this.pref('cosx-site-lang', 'en'), theme: this.pref('cosx-site-theme', 'light') });
    window.addEventListener('storage', this._sync);
  }
  componentWillUnmount() {
    window.removeEventListener('storage', this._sync);
    clearTimeout(this._t);
  }
  pv(g) {
    var P =
      {
        paper: ['#FEFDFB', '#F5F2EC', '#ECE9E3', '#111111', '#696969', 'rgba(17,17,17,.10)', 'rgba(17,17,17,.06)', '#F7F6F4'],
        yellow: ['#FFE3A0', '#FFF1D6', '#F7D98F', '#111111', 'rgba(17,17,17,.7)', 'rgba(17,17,17,.14)', 'rgba(17,17,17,.08)', '#F7D98F'],
        ink: ['#111111', '#1B1B1B', '#232221', '#F5F2EC', '#9E9E9E', 'rgba(245,242,236,.18)', 'rgba(245,242,236,.09)', '#1F1E1D'],
      }[g] || [];
    return { bgPage: P[0], bgSunk: P[1], bgWell: P[2], tp: P[3], ts: P[4], rule: P[5], ruleSoft: P[6], hover: P[7] };
  }
  seg(key, opts) {
    var set = {},
      on = {},
      self = this;
    opts.forEach(function (o) {
      set[key + '_' + o] = function () {
        self.setState({ [key]: o });
      };
      var a = self.state[key] === o;
      on[key + '_' + o] = { bg: a ? 'var(--brand-field, var(--yellow))' : 'transparent', fg: a ? 'var(--ink)' : 'var(--text-primary)' };
    });
    return { set: set, on: on };
  }
  merge(parts) {
    var set = {},
      on = {};
    parts.forEach(function (p) {
      Object.assign(set, p.set);
      Object.assign(on, p.on);
    });
    return { set: set, on: on };
  }
  copyText(txt) {
    try {
      navigator.clipboard && navigator.clipboard.writeText(txt);
    } catch (e) {}
    this.setState({ copied: true });
    clearTimeout(this._t);
    this._t = setTimeout(() => this.setState({ copied: false }), 1400);
  }

  base() {
    var s = this.state,
      zh = s.lang === 'zh',
      dark = s.theme === 'dark';
    return {
      lang: s.lang,
      theme: s.theme,
      zh: zh,
      en: !zh,
      dark: dark,
      T: this.dict[zh ? 'zh' : 'en'],
      dz: zh ? 'inline' : 'none',
      de: zh ? 'none' : 'inline',
      htmlLang: zh ? 'zh-CN' : 'en-GB',
      modeClass: dark ? 'ink-mode' : '',
      ground: dark ? 'ink' : 'paper',
      lightD: dark ? 'none' : 'block',
      darkD: dark ? 'block' : 'none',
      copyLabel: s.copied ? (zh ? '已复制' : 'Copied') : zh ? '复制' : 'Copy',
      copyIcon: s.copied ? 'check' : 'copy',
      toggleLang: () => {
        var l = zh ? 'en' : 'zh';
        this.save('cosx-site-lang', l);
        this.setState({ lang: l });
      },
      toggleTheme: () => {
        var t = dark ? 'light' : 'dark';
        this.save('cosx-site-theme', t);
        this.setState({ theme: t });
      },
      go: {
        colour: () => {
          location.href = '/colour';
        },
        button: () => {
          location.href = '/button';
        },
        spec: () => {
          location.href = '../ui-spec/MetaRoom Components.dc.html';
        },
        portal: () => {
          location.href = '../pages/MetaRoom Customer Portal.dc.html';
        },
      },
    };
  }
  page(b) {
    var s = this.state,
      zh = b.zh,
      self = this,
      h = React.createElement;
    var defs = {
      copy: ['neutral', zh ? '链接已复制。' : 'Link copied.', '', ''],
      move: ['complete', zh ? '3 个文件已移到归档。' : '3 files moved to Archive.', '', zh ? '撤销' : 'Undo'],
      fail: [
        'error',
        zh ? '无法重命名文件夹。' : 'Couldn\u2019t rename the folder.',
        zh ? '已有同名文件。' : 'A file with that name already exists.',
        zh ? '重试' : 'Retry',
      ],
    };
    var fire = {};
    Object.keys(defs).forEach(function (k) {
      fire[k] = function () {
        var id = Date.now() + Math.random();
        var list = self.state.list.concat([{ id: id, k: k }]).slice(-3);
        self.setState({ list: list });
        setTimeout(
          function () {
            self.setState(function (st) {
              return {
                list: st.list.filter(function (t) {
                  return t.id !== id;
                }),
              };
            });
          },
          defs[k][3] ? 8000 : 4000,
        );
      };
    });
    return {
      pv: this.pv(b.dark ? 'ink' : 'paper'),
      fire: fire,
      toasts: s.list.map(function (t) {
        var d = defs[t.k],
          close = function () {
            self.setState(function (st) {
              return {
                list: st.list.filter(function (x) {
                  return x.id !== t.id;
                }),
              };
            });
          };
        return {
          status: d[0],
          title: d[1],
          body: d[2],
          close: close,
          action: d[3]
            ? h(
                'button',
                {
                  type: 'button',
                  onClick: close,
                  style: {
                    border: 'none',
                    background: 'none',
                    color: '#FFD166',
                    font: '600 13px var(--font-sans)',
                    cursor: 'pointer',
                    padding: 0,
                  },
                },
                d[3],
              )
            : null,
        };
      }),
    };
  }
  renderVals() {
    var b = this.base();
    return Object.assign(b, this.page(b));
  }
}

